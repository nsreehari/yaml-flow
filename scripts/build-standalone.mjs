#!/usr/bin/env node

import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { transform } from 'esbuild';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const root = path.resolve(__dirname, '..');
const outDir = path.join(root, 'standalone');
const shouldMinifyJs = !process.argv.includes('--no-minify-js');

const runtimeRootEntries = [
  'board-live-cards-cli.js',
  'card-store.js',
];

const runtimeDirs = [
  'dist/cli/node',
  'dist/pycli',
  'pycli/main',
  'pycli/sub',
];

const runtimeFiles = [
  'pycli/requirements.txt',
  'examples/browser/boards/portfolio-tracker/portfolio-tracker.py',
  'examples/browser/boards/portfolio-tracker/portfolio-tracker-fetch-prices.py',
];

const copiedPkgs = new Set();

function pkgPath(baseDir, pkgName) {
  return path.join(baseDir, 'node_modules', ...pkgName.split('/'));
}

async function exists(p) {
  try {
    await fs.access(p);
    return true;
  } catch {
    return false;
  }
}

async function copyIntoDist(relPath) {
  const src = path.join(root, relPath);
  const dst = path.join(outDir, relPath);
  await fs.mkdir(path.dirname(dst), { recursive: true });
  await fs.cp(src, dst, { recursive: true });
}

async function copyPackageWithDeps(pkgName, optional = false) {
  if (copiedPkgs.has(pkgName)) return;

  const srcPkgDir = pkgPath(root, pkgName);
  if (!(await exists(srcPkgDir))) {
    if (optional) return;
    throw new Error(`Missing runtime dependency in node_modules: ${pkgName}`);
  }

  copiedPkgs.add(pkgName);

  const dstPkgDir = pkgPath(outDir, pkgName);
  await fs.mkdir(path.dirname(dstPkgDir), { recursive: true });
  await fs.cp(srcPkgDir, dstPkgDir, { recursive: true });

  const pkgJsonPath = path.join(srcPkgDir, 'package.json');
  if (!(await exists(pkgJsonPath))) return;

  const pkgJson = JSON.parse(await fs.readFile(pkgJsonPath, 'utf-8'));
  const deps = Object.keys(pkgJson.dependencies ?? {});
  const optionalDeps = Object.keys(pkgJson.optionalDependencies ?? {});

  for (const dep of deps) {
    await copyPackageWithDeps(dep, false);
  }
  for (const dep of optionalDeps) {
    await copyPackageWithDeps(dep, true);
  }
}

async function writeReadme() {
  const readme = [
    '# yaml-flow standalone',
    '',
    'Standalone pycli distribution generated by `npm run standalone`.',
    '',
    '## Requirements',
    '- Python 3.12',
    '- Node.js 18+ (required for detached process callbacks from pycli host bridge)',
    '',
    '## Setup',
    '1. `python -m pip install -r pycli/requirements.txt`',
    '',
    '## Usage',
    'Run from this directory root:',
    '- `python pycli/main/board_live_cards_pycli.py --help`',
    '- `python pycli/main/board_live_cards_pycli.py board-status --base-ref ::fs-path::<BOARD_DIR>`',
    '- `python examples/browser/boards/portfolio-tracker/portfolio-tracker.py`',
    '',
    'Optional notifications:',
    '- add `--notify-channel <channel>` to board commands',
  ].join('\n');

  await fs.writeFile(path.join(outDir, 'README-STANDALONE.md'), readme, 'utf-8');
}

async function walkFiles(dir) {
  const out = [];
  const entries = await fs.readdir(dir, { withFileTypes: true });
  for (const entry of entries) {
    const p = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      const nested = await walkFiles(p);
      out.push(...nested);
    } else {
      out.push(p);
    }
  }
  return out;
}

async function minifyStandaloneJs() {
  const staticTargets = [
    path.join(outDir, 'board-live-cards-cli.js'),
    path.join(outDir, 'card-store.js'),
  ];

  const distRoot = path.join(outDir, 'dist');
  const distFiles = (await exists(distRoot)) ? await walkFiles(distRoot) : [];
  const distTargets = distFiles.filter(p => p.endsWith('.js') || p.endsWith('.cjs'));
  const mapFiles = distFiles.filter(p => p.endsWith('.map'));

  const allTargets = [...staticTargets, ...distTargets];

  for (const filePath of allTargets) {
    if (!(await exists(filePath))) continue;
    const source = await fs.readFile(filePath, 'utf-8');
    const lines = source.split('\n');
    const shebang = lines[0].startsWith('#!') ? lines[0] : '';
    const body = shebang ? lines.slice(1).join('\n') : source;

    const result = await transform(body, {
      loader: 'js',
      minify: true,
      legalComments: 'none',
      target: 'es2022',
    });

    const output = shebang ? `${shebang}\n${result.code}` : result.code;
    await fs.writeFile(filePath, output, 'utf-8');
  }

  for (const mapFile of mapFiles) {
    await fs.rm(mapFile, { force: true });
  }
}

async function main() {
  await fs.rm(outDir, { recursive: true, force: true });
  await fs.mkdir(outDir, { recursive: true });

  for (const rel of runtimeRootEntries) {
    await copyIntoDist(rel);
  }
  for (const rel of runtimeDirs) {
    await copyIntoDist(rel);
  }
  for (const rel of runtimeFiles) {
    await copyIntoDist(rel);
  }

  const projectPkg = JSON.parse(await fs.readFile(path.join(root, 'package.json'), 'utf-8'));
  const topLevelRuntimeDeps = [
    ...Object.keys(projectPkg.dependencies ?? {}),
    ...Object.keys(projectPkg.optionalDependencies ?? {}),
  ];

  for (const dep of topLevelRuntimeDeps) {
    await copyPackageWithDeps(dep, true);
  }

  if (shouldMinifyJs) {
    await minifyStandaloneJs();
  }

  await writeReadme();

  console.log(`standalone generated at: ${outDir}${shouldMinifyJs ? ' (js minified)' : ''}`);
}

main().catch((err) => {
  console.error(err instanceof Error ? err.message : String(err));
  process.exit(1);
});
